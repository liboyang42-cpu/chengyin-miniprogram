const DEFAULT_TYPE = 'user_agreement';

// 弹窗那侧用的短别名(type="service" / type="deregister"),映射到上面的正式 key。
// 路由页仍用正式 key(?type=user_agreement),两种写法都能取到同一份文档。
const TYPE_ALIAS = {
  service: 'user_agreement',
  deregister: 'cancellation_notice',
};

function resolveKey(type) {
  const key = TYPE_ALIAS[type] || type;
  return DOCS[key] ? key : DEFAULT_TYPE;
}

// 未知 type 一律回退到用户服务协议,不返回 undefined 让调用方渲染空白页
function getDoc(type) {
  return DOCS[resolveKey(type)];
}

module.exports = { DOCS, DEFAULT_TYPE, TYPE_ALIAS, resolveKey, getDoc };
